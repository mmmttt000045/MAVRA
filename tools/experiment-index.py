#!/usr/bin/env python3
"""Render or check the experiment index (exp/README.md) using only the Python standard library."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'exp/catalog.json'
INDEX = ROOT / 'exp/README.md'
SECTIONS = {
    'motivation': '§2.1 Workload Characterization and Motivation',
    'q1': '§6.2 Q1: Multi-Agent Population Sharing and Multi-Schema Generality',
    'q2': '§6.3 Q2: Semantic Lookup Scaling and Selective Routing',
    'q3': '§6.4 Q3: Maintenance Under Database Evolution',
    'q4': '§6.5 Q4: Cross-Cutoff Predictive Feature Reuse (RelBench)',
    'q5': '§6.6 Q5: Mechanism Isolation, Policy Replay, and Warehouse Scaling',
}


def validate(catalog):
    entries = catalog['experiments']
    ids = [entry['id'] for entry in entries]
    if len(ids) != len(set(ids)):
        raise ValueError('Duplicate experiment IDs')
    directories = {p.name for p in (ROOT / 'exp').iterdir() if p.is_dir()}
    if set(ids) != directories:
        raise ValueError(f'Catalog/directory mismatch: {sorted(set(ids) ^ directories)}')
    for entry in entries:
        if not re.fullmatch(r'[a-z][a-z0-9-]*', entry['id']):
            raise ValueError(f'Invalid experiment ID: {entry["id"]}')
        if entry['section'] not in SECTIONS:
            raise ValueError(f'Unknown section: {entry["section"]}')
        for field in ('title', 'scope', 'raw_data', 'code_record'):
            if not entry[field].strip():
                raise ValueError(f'{entry["id"]}: missing {field}')
        paths = [f'exp/{entry["id"]}/README.md', *entry['evidence'], *entry['analysis'], *entry['outputs']]
        for value in paths:
            path = Path(value)
            if path.is_absolute() or '..' in path.parts or not (ROOT / path).is_file():
                raise ValueError(f'{entry["id"]}: missing or invalid file: {value}')
    return entries


def link(path):
    relative = path[4:] if path.startswith('exp/') else '../' + path
    return f'[{Path(path).name}]({relative})'


def render(entries):
    lines = [
        '# Experiment Index',
        '',
        '<!-- Generated by tools/experiment-index.py from exp/catalog.json; edit exp/catalog.json rather than this file. -->',
        '',
        'This directory contains the curated experimental benchmarks, declarative schema specifications, analysis scripts, and aggregated statistical summaries for *MAVRA: Sharing and Maintaining Executable Knowledge for Data Agents*.',
        '',
        'Live benchmark runs write transient execution logs and generated artifacts under Git-ignored `results/` (including LaTeX macros in `results/gen/` and vector figures in `results/figures/`), while clean benchmark inputs and aggregated statistical summaries are versioned here. Machine-readable metadata is stored in [catalog.json](catalog.json).',
        '',
    ]
    for section, label in SECTIONS.items():
        group = [entry for entry in entries if entry['section'] == section]
        if not group:
            continue
        lines += [f'## {label}', '', '| Experiment | Paper Mapping & Scope |', '| --- | --- |']
        for entry in group:
            lines.append(f'| [{entry["id"]}]({entry["id"]}/README.md)<br>{entry["title"]} | {entry["scope"]} |')
        lines.append('')
    lines += [
        '## Evidence and Reproduction Entrypoints',
        '',
        '| Experiment | Benchmark Inputs & Summaries | Analysis & Runner Scripts | Derived Outputs |',
        '| --- | --- | --- | --- |',
    ]
    for entry in entries:
        columns = [', '.join(link(p) for p in entry[field]) or '—' for field in ('evidence', 'analysis', 'outputs')]
        lines.append(f'| {entry["id"]} | ' + ' | '.join(columns) + ' |')
    lines += [
        '',
        '## Benchmark Artifacts and CLI Entrypoints',
        '',
        '| Experiment | Curated Data & Inputs | Benchmark CLI & Configuration |',
        '| --- | --- | --- |',
    ]
    for entry in entries:
        lines.append(f'| {entry["id"]} | {entry["raw_data"]} | {entry["code_record"]} |')
    lines += [
        '',
        '## Index Validation',
        '',
        'After editing `exp/catalog.json`, regenerate this index from the repository root with `python3 tools/experiment-index.py`. Pass `--check` in CI to verify directory coverage, file references, and index synchronization without running benchmarks.',
        '',
    ]
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='validate without writing')
    args = parser.parse_args()
    try:
        entries = validate(json.loads(CATALOG.read_text(encoding='utf-8')))
        content = render(entries)
        if args.check:
            if not INDEX.is_file() or INDEX.read_text(encoding='utf-8') != content:
                raise ValueError('exp/README.md is stale; run python3 tools/experiment-index.py')
        else:
            INDEX.write_text(content, encoding='utf-8')
    except (ValueError, KeyError, OSError) as error:
        parser.exit(1, f'{error}\n')
    print(f'{len(entries)} experiments: coverage, references, and index OK')


if __name__ == '__main__':
    main()
