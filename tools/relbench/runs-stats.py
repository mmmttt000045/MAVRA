#!/usr/bin/env python3
"""MAVRA against No memory over the paired runs of the five-cutoff RelBench study (exp/2026-10-20-relbench, README 4.y):
macros in overleaf/gen/relbench-runs.tex. Same rules as paper-stats.py: a session without a valid solution takes the
entity-reference test score of its (task, cutoff) in that run; per task, the test score is averaged over every cutoff
of every finished run pair; the pre-registered margins (AUC within 0.01, MAE within 2%) decide the tasks within them.
Reuse-stage tokens (cutoffs 2-5, memory operations included) are compared per run.

  python3 tools/relbench/runs-stats.py --out overleaf/gen
"""
import argparse
import importlib.util
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("compare_stats", os.path.join(HERE, "compare-stats.py"))
cs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cs)

RUNS = {"rel-stack": ("Stack", "results/relbench-pilot3/{arm}-rel-stack-r{run}"),
        "rel-trial": ("Trial", "results/relbench-main/{arm}-rel-trial-r{run}")}
ARMS = {"none": "none", "mavra": "mavra-select"}
RUN_IDS = (1, 2)


def finished(path):
    try:
        r = json.load(open(os.path.join(path, "run.json")))
    except (OSError, ValueError):
        return False
    return bool(r.get("finished")) and not r.get("error")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    macros = {"RbRunsN": "--", "RbRunsNotWorse": "--", "RbRunsTasks": "--", "RbRunsTokSaveMin": "--", "RbRunsTokSaveMax": "--"}
    report = {}
    within, total, saves = 0, 0, []
    runs_used = None
    for db, (pre, pattern) in RUNS.items():
        pairs = [r for r in RUN_IDS if all(finished(pattern.format(arm=f, run=r)) for f in ARMS.values())]
        runs_used = len(pairs) if runs_used is None else min(runs_used, len(pairs))
        if not pairs:
            continue
        scores = {arm: {} for arm in ARMS}
        for r in pairs:
            data = {arm: cs.load(pattern.format(arm=f, run=r)) for arm, f in ARMS.items()}
            if set(data["none"]) != set(data["mavra"]):
                raise SystemExit(f"{db} run {r}: the two arms cover different sessions")
            ref_run = json.load(open(os.path.join(pattern.format(arm="none", run=r), "run.json")))
            ref = {(t, c["k"]): v.get("test") for c in ref_run["cutoffs"] for t, v in (c.get("reference") or {}).items()}
            late = [key for key in data["none"] if key[1] >= 2]
            tok = {arm: sum(data[arm][key]["tokens"] for key in late) for arm in ARMS}
            save = 100 * (1 - tok["mavra"] / tok["none"])
            saves.append(save)
            report.setdefault(db, {})[f"run{r}"] = {"reuse_tokens": tok, "token_save_pct": round(save, 1)}
            macros[f"RbRuns{pre}TokSaveR{'ab'[r - 1]}"] = f"{save:.0f}"
            for arm in ARMS:
                for key, v in data[arm].items():
                    test = v["test"] if v["test"] is not None else ref.get(key)
                    scores[arm].setdefault(key[0], []).append(test)
                    if key[1] == 1:  # the task's first learning session (empty memory for MAVRA's first task of a run)
                        i = sorted({x[0] for x in data["none"]}).index(key[0])
                        macros[f"RbRuns{pre}{'Mavra' if arm == 'mavra' else 'None'}KoneQ{'ABC'[i]}R{'ab'[r - 1]}"] = \
                            f"{test:.4f}" if test < 1 else f"{test:.2f}"
        for i, task in enumerate(sorted(scores["none"])):
            higher = cs.load(pattern.format(arm="none", run=pairs[0]))[(task, 1)]["higher"]
            m, n = statistics.mean(scores["mavra"][task]), statistics.mean(scores["none"][task])
            ok = (m >= n - 0.01) if higher else (m <= n * 1.02)
            within += ok
            total += 1
            report[db][task] = {"mavra": m, "none": n, "within": ok, "sessions": len(scores["mavra"][task])}
            for arm, v in (("Mavra", m), ("None", n)):
                macros[f"RbRuns{pre}{arm}Q{'ABC'[i]}"] = f"{v:.4f}" if v < 1 else f"{v:.2f}"
    if total:
        macros.update({"RbRunsN": str(runs_used), "RbRunsNotWorse": str(within), "RbRunsTasks": str(total),
                       "RbRunsTokSaveMin": f"{min(saves):.0f}", "RbRunsTokSaveMax": f"{max(saves):.0f}"})
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "relbench-runs.tex"), "w") as f:
        f.write("% generated by tools/relbench/runs-stats.py; do not edit\n")
        for k, v in sorted(macros.items()):
            f.write(f"\\providecommand{{\\{k}}}{{}}\\renewcommand{{\\{k}}}{{{v}}}\n")
    print(json.dumps({"macros": macros, "report": report}, indent=1, default=str))


if __name__ == "__main__":
    main()
