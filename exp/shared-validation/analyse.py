#!/usr/bin/env python3
"""Aggregate the shared-validation scaling benchmark (postgres_shared_validation_scaling; no model calls).

When run without `--results-dir`, loads archived `stats.json` directly and emits all `Sv*`
LaTeX macros to `--tex` without overwriting `stats.json`. When `--results-dir` is passed,
aggregates `cell-*.json` files across policies, arrival patterns, and agent counts.
"""
import argparse
import json
from pathlib import Path
from statistics import median

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
POLICIES = ['per-agent', 'full-recheck', 'mavra']
ARRIVALS = ['staggered', 'simultaneous']


def aggregate_live(results_dir: Path) -> dict:
    cells = [json.loads(p.read_text(encoding='utf-8')) for p in sorted(results_dir.glob('cell-*.json'))]
    if not cells:
        raise SystemExit(f'No cell-*.json files found in {results_dir}; refusing to overwrite summary')
    agents = sorted({c['agents'] for c in cells})
    out = {'cells': len(cells), 'agents': agents, 'groups': [], 'unavailable': sum(c['unavailable'] for c in cells)}
    for policy in POLICIES:
        for arrival in ARRIVALS:
            for n in agents:
                xs = [c for c in cells if c['policy'] == policy and c['arrival'] == arrival and c['agents'] == n]
                if not xs:
                    continue
                checks = [c['db']['by_kind']['metric'][0] for c in xs]
                secs = [c['db']['db_ms'] / 1000 for c in xs]
                out['groups'].append({
                    'policy': policy,
                    'arrival': arrival,
                    'agents': n,
                    'blocks': len(xs),
                    'checks': {'median': median(checks), 'min': min(checks), 'max': max(checks)},
                    'db_s': {'median': median(secs), 'min': min(secs), 'max': max(secs)},
                    'uses': n * xs[0]['definitions'],
                })
    return out


def build_macros(out: dict) -> dict[str, str]:
    def g(policy, arrival, n):
        return next(x for x in out['groups'] if x['policy'] == policy and x['arrival'] == arrival and x['agents'] == n)

    top = max(out['agents'])
    mac = {'SvAgentsMax': str(top), 'SvCells': str(out['cells']), 'SvUnavailable': str(out['unavailable'])}
    for arrival, tag in [('staggered', 'Stag'), ('simultaneous', 'Sim')]:
        for policy, ptag in [('per-agent', 'Private'), ('full-recheck', 'Full'), ('mavra', 'Mavra')]:
            x = g(policy, arrival, top)
            mac[f'Sv{tag}{ptag}Checks'] = f"{x['checks']['median']:.0f}"
            mac[f'Sv{tag}{ptag}DbS'] = f"{x['db_s']['median']:.1f}"
            mac[f'Sv{tag}{ptag}OneDbS'] = f"{g(policy, arrival, 1)['db_s']['median']:.1f}"
        m = g('mavra', arrival, top)['db_s']['median']
        mac[f'Sv{tag}PrivateRatio'] = f"{g('per-agent', arrival, top)['db_s']['median'] / m:.0f}"
        mac[f'Sv{tag}FullRatio'] = f"{g('full-recheck', arrival, top)['db_s']['median'] / m:.1f}"
    return mac


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--results-dir', type=Path, default=None, help='Live cell-*.json directory')
    ap.add_argument('--out', type=Path, default=HERE / 'stats.json', help='Summary JSON path')
    ap.add_argument('--tex', type=Path, default=ROOT / 'results/gen/shared-validation.tex', help='Output LaTeX macro path')
    a = ap.parse_args()

    if a.results_dir is None:
        if not a.out.is_file():
            raise SystemExit(f'Missing archived {a.out}')
        out = json.loads(a.out.read_text(encoding='utf-8'))
    else:
        out = aggregate_live(a.results_dir)
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(json.dumps(out, indent=2) + '\n', encoding='utf-8')

    mac = build_macros(out)
    tex = ['% Generated by exp/shared-validation/analyse.py; do not edit.']
    tex += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in sorted(mac.items())]
    a.tex.parent.mkdir(parents=True, exist_ok=True)
    a.tex.write_text('\n'.join(tex) + '\n', encoding='utf-8')
    for x in out['groups']:
        print(
            x['policy'].ljust(13),
            x['arrival'].ljust(12),
            f"n={x['agents']:2d}",
            f"checks={x['checks']['median']:5.0f}",
            f"db={x['db_s']['median']:7.1f}s [{x['db_s']['min']:.1f}-{x['db_s']['max']:.1f}]",
        )
    print(f'wrote {len(mac)} macros to {a.tex}')


if __name__ == '__main__':
    main()
