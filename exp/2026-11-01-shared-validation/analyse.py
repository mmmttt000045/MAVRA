#!/usr/bin/env python3
"""Aggregate the shared-validation scaling benchmark (postgres_shared_validation_scaling; no model calls).

For each policy, arrival and agent count: validation checks executed after the update
(maintenance queries) and database time of the use phase, median over the three
randomized blocks with the observed range. Writes stats.json here and
overleaf/gen/shared-validation.tex.
Usage: analyse.py RESULTS_DIR [--tex PATH]
"""
import argparse
import json
from pathlib import Path
from statistics import median

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
POLICIES = ['per-agent', 'full-recheck', 'mavra']
ARRIVALS = ['staggered', 'simultaneous']


def main():
    a = argparse.ArgumentParser()
    a.add_argument('results')
    a.add_argument('--tex', default=str(ROOT / 'overleaf/gen/shared-validation.tex'))
    a = a.parse_args()
    cells = [json.loads(p.read_text()) for p in sorted(Path(a.results).glob('cell-*.json'))]
    agents = sorted({c['agents'] for c in cells})
    out = {'cells': len(cells), 'agents': agents, 'groups': [], 'unavailable': sum(c['unavailable'] for c in cells)}
    for policy in POLICIES:
        for arrival in ARRIVALS:
            for n in agents:
                xs = [c for c in cells if c['policy'] == policy and c['arrival'] == arrival and c['agents'] == n]
                if not xs:
                    continue
                checks = [c['db']['by_kind']['metric'][0] for c in xs]
                secs = [c['db']['db_ms'] / 1000 for c in xs]
                out['groups'].append({'policy': policy, 'arrival': arrival, 'agents': n, 'blocks': len(xs),
                                      'checks': {'median': median(checks), 'min': min(checks), 'max': max(checks)},
                                      'db_s': {'median': median(secs), 'min': min(secs), 'max': max(secs)},
                                      'uses': n * xs[0]['definitions']})
    (HERE / 'stats.json').write_text(json.dumps(out, indent=2) + '\n')

    def g(policy, arrival, n):
        return next(x for x in out['groups'] if x['policy'] == policy and x['arrival'] == arrival and x['agents'] == n)

    top = max(agents)
    mac = {'SvAgentsMax': str(top), 'SvCells': str(len(cells)), 'SvUnavailable': str(out['unavailable'])}
    for arrival, tag in [('staggered', 'Stag'), ('simultaneous', 'Sim')]:
        for policy, ptag in [('per-agent', 'Private'), ('full-recheck', 'Full'), ('mavra', 'Mavra')]:
            x = g(policy, arrival, top)
            mac[f'Sv{tag}{ptag}Checks'] = f"{x['checks']['median']:.0f}"
            mac[f'Sv{tag}{ptag}DbS'] = f"{x['db_s']['median']:.1f}"
            mac[f'Sv{tag}{ptag}OneDbS'] = f"{g(policy, arrival, 1)['db_s']['median']:.1f}"
        m = g('mavra', arrival, top)['db_s']['median']
        mac[f'Sv{tag}PrivateRatio'] = f"{g('per-agent', arrival, top)['db_s']['median'] / m:.0f}"
        mac[f'Sv{tag}FullRatio'] = f"{g('full-recheck', arrival, top)['db_s']['median'] / m:.1f}"
    tex = ['% Generated by exp/2026-11-01-shared-validation/analyse.py; do not edit.']
    tex += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in sorted(mac.items())]
    Path(a.tex).write_text('\n'.join(tex) + '\n')
    for x in out['groups']:
        print(x['policy'].ljust(13), x['arrival'].ljust(12), f"n={x['agents']:2d}", f"checks={x['checks']['median']:5.0f}",
              f"db={x['db_s']['median']:7.1f}s [{x['db_s']['min']:.1f}-{x['db_s']['max']:.1f}]")
    print(mac)


if __name__ == '__main__':
    main()
