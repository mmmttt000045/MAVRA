#!/usr/bin/env python3
"""Sustained reads and writes (postgres_sustained_writes): cells of the first run, trigger overhead of the second
(SW_OVERHEAD_ONLY). Writes summary.json and overleaf/gen/sustained.tex."""
import glob, json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
cells = []
for f in sorted(glob.glob(str(HERE / "sustained-writes-*/cell-*.json"))):
    cells.append(json.loads(Path(f).read_text()))
over = None
for f in sorted(glob.glob(str(HERE / "sustained-writes-*/report.json"))):
    r = json.loads(Path(f).read_text())["report"]
    if "trigger_overhead" in r:
        over = r["trigger_overhead"]
rows = {}
for c in cells:
    a = c["condition_actions"]
    executed = a.get("executed", 0)
    reused = a.get("reused", 0) + a.get("implied", 0) + a.get("merged", 0)
    rows[(c["policy"], c["rate"])] = {"writes": c["writes"], "executed": executed, "reused": reused,
                                      "db_ms_per_use": c["db"]["db_ms"] / c["uses"], "uses": c["uses"]}
summary = {"rows": {f"{p}@{r}": v for (p, r), v in rows.items()}, "trigger_overhead": over}
(HERE / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
mac = {}
tag = {"0/1": "Zero", "1/8": "Low", "1/2": "Mid", "2/1": "High"}
for (p, r), v in rows.items():
    t = ("Mavra" if p == "mavra" else "Full") + tag[r]
    mac[f"Sw{t}Checks"] = f"{v['executed']:,}".replace(",", "{,}")
    mac[f"Sw{t}Ms"] = f"{v['db_ms_per_use']:.0f}"
    mac[f"Sw{tag[r]}Writes"] = str(v["writes"])
m, f = rows[("mavra", "2/1")], rows[("full-recheck", "2/1")]
mac["SwHighReusePct"] = f"{100 * m['reused'] / (m['reused'] + m['executed']):.0f}"
mac["SwHighRatio"] = f"{f['executed'] / m['executed']:.1f}"
mac["SwUses"] = f"{m['uses']:,}".replace(",", "{,}")
mac["SwTrigMs"] = f"{over['median_ms_with_trigger'] - over['median_ms_without']:.1f}"
mac["SwTrigPct"] = f"{100 * (over['median_ms_with_trigger'] / over['median_ms_without'] - 1):.1f}"
tex = ["% Generated by exp/2026-11-11-maint-hardening/sustained/macros.py; do not edit."]
tex += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(mac.items())]
(ROOT / "overleaf/gen/sustained.tex").write_text("\n".join(tex) + "\n")
print("\n".join(tex))
