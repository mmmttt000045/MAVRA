#!/usr/bin/env python3
"""Change-study answers split by whether the agent answered from a served definition (a declared, valid revision) or
from its own SQL (definition withheld, unavailable, or not learned). Runs on the cells directory; writes
served-split.json here and overleaf/gen/served-split.tex.
Usage: served-split.py CELLS_DIR"""
import collections, glob, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
P = json.loads((ROOT / "exp/2026-11-01-change-study/protocol.json").read_text())
inv = {c: g for g, cs in P["groups"].items() for c in cs}
out = {}
for arm in ["mavra", "recheck"]:
    c = collections.Counter()
    for f in glob.glob(f"{sys.argv[1]}/*-r*-{arm}/metric-*/task-journal.jsonl"):
        for line in open(f):
            r = json.loads(line)
            if r["phase"] == "learn":
                continue
            mu = r.get("metric_use") or {}
            used = bool(mu.get("declared")) and mu.get("bad_declared", 0) == 0
            c[f'{inv.get(r["phase"], "holdout")}|{"def" if used else "own"}|{r["outcome"]}'] += 1
    out[arm] = dict(c)
(HERE / "served-split.json").write_text(json.dumps(out, indent=2) + "\n")
def tot(arm, src=None, outcome=None, group=None):
    return sum(v for k, v in out[arm].items() if (src is None or k.split("|")[1] == src) and
               (outcome is None or k.split("|")[2] == outcome) and (group is None or k.split("|")[0] == group))
mac = {"SsMavraServed": tot("mavra", "def"), "SsMavraServedWrong": tot("mavra", "def", "wrong"),
       "SsMavraOwnWrong": tot("mavra", "own", "wrong"), "SsMavraBreakServed": tot("mavra", "def", group="covered_breaks"),
       "SsBreakN": tot("mavra", group="covered_breaks"), "SsRecheckBreakServed": tot("recheck", "def", group="covered_breaks"),
       "SsRecheckBreakOwn": tot("recheck", "own", group="covered_breaks"),
       "SsRecheckBreakOwnClarify": tot("recheck", "own", "clarify", "covered_breaks"),
       "SsRecheckBreakOwnWrong": tot("recheck", "own", "wrong", "covered_breaks")}
import re
cs = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", (ROOT / "overleaf/gen/change-study.tex").read_text()))
mac["CsBreakMavraGainRecheck"] = f"{float(cs['CsBreakMavra']) - float(cs['CsBreakRecheck']):.1f}"
mac["CsBreakRecheckTokRatio"] = f"{float(cs['CsBreakRecheckTokK']) / float(cs['CsBreakMavraTokK']):.1f}"
tex = ["% Generated by exp/2026-11-11-maint-hardening/served-split.py; do not edit."]
tex += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(mac.items())]
(ROOT / "overleaf/gen/served-split.tex").write_text("\n".join(tex) + "\n")
print("\n".join(tex))
