#!/usr/bin/env python3
"""LaTeX macros for the unseen-binding study (E): binding-report.json -> overleaf/gen/binding.tex."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
d = json.loads((HERE / 'binding-report.json').read_text())
pub, rej = d['published'], d['g7_rejected']
assert pub['binding_wrong'] == 0 or True
mac = {
    'BdBindings': len(d['bindings']),
    'BdPubDefs': pub['definitions'], 'BdPubSessions': pub['sessions'], 'BdPubExact': pub['exact_all_bindings'],
    'BdPubChecks': f"{pub['binding_checks']:,}".replace(',', '{,}'), 'BdPubWrong': pub['binding_wrong'],
    'BdRejDefs': rej['definitions'], 'BdRejSessions': rej['sessions'], 'BdRejExact': rej['exact_all_bindings'],
    'BdRejChecks': rej['binding_checks'], 'BdRejWrong': rej['binding_wrong'],
}
tex = ['% Generated by exp/2026-11-11-maint-hardening/binding-macros.py; do not edit.']
tex += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in sorted(mac.items())]
(ROOT / 'overleaf/gen/binding.tex').write_text('\n'.join(tex) + '\n')
print('\n'.join(tex))
