#!/usr/bin/env python3
"""Fixed-library replay by maintenance policy on four schemas (no model calls).

When run without `--reports-dir`, loads archived `replay-policies.json` directly and
emits the `Rp*` LaTeX macros to `--tex` without overwriting `replay-policies.json`.
When `--reports-dir` is supplied, aggregates per-schema `replay-*/report.json` files
across TPC-DS, TPC-H, SSB, and BIRD `financial` and updates `--out`.
"""
import argparse
from collections import Counter
import glob
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SCHEMAS = ('tpcds', 'tpch', 'ssb', 'financial')
SCOPES = {
    'Benign': ['append', 'backfill', 'correct', 'addcol'],
    'Break': ['status', 'revision', 'dupload', 'dimhist', 'latekey'],
    'Outside': ['unit', 'mirror'],
}
POLICIES = [('revoke', 'Revoke'), ('schema', 'Schema'), ('tabletest', 'Tests'), ('condition', 'Mavra')]
CLASS = {'correct': 'C', 'served_wrong': 'W', 'unavailable_needed': 'R', 'unavailable_unneeded': 'R'}


def key(r):
    return (r['lib'].split('/')[-1], r['change'], r['entry'], r['task'])


def build_macros(table: dict) -> dict[str, str]:
    mac = {}
    for p, tag in POLICIES:
        for s in SCOPES:
            c = table[p][s]
            for cls in 'CWR':
                mac[f'Rp{tag}{s}{cls}'] = f'{c.get(cls, 0):,}'.replace(',', '{,}')
            mac[f'Rp{s}N'] = f"{c['n']:,}".replace(',', '{,}')
    total = sum(table['condition'][s]['n'] for s in SCOPES)
    mac['RpTotal'] = f'{total:,}'.replace(',', '{,}')
    m = table['condition']['Break']
    mac['RpMavraBreakCPct'] = f"{100 * m.get('C', 0) / m['n']:.0f}"
    mac['RpSchemaBreakWPct'] = f"{100 * table['schema']['Break'].get('W', 0) / table['schema']['Break']['n']:.0f}"
    return mac


def aggregate_live(reports_dir: Path) -> dict:
    table = {p: {s: Counter() for s in SCOPES} for p, _ in POLICIES}
    per_change = {}
    summary = {}
    for ds in SCHEMAS:
        reports = glob.glob(str(reports_dir / ds / 'replay-*/report.json'))
        if len(reports) != 1:
            raise SystemExit(f'Expected exactly one replay report for {ds} under {reports_dir}, found {reports}')
        outs = json.loads(Path(reports[0]).read_text(encoding='utf-8'))['outcomes']
        rows = {
            p: {key(r): r for r in outs if r['policy'] == p and r['oracle'] == 'snapshot'}
            for p, _ in POLICIES
        }
        common = set.intersection(*[set(v) for v in rows.values()])
        summary[ds] = {'common': len(common)}
        for p, _ in POLICIES:
            for k in common:
                r = rows[p][k]
                scope = next((s for s, cs in SCOPES.items() if r['change'] in cs), None)
                if scope is None:
                    continue
                table[p][scope][CLASS[r['class']]] += 1
                table[p][scope]['n'] += 1
                per_change.setdefault(f'{ds}/{r["change"]}', {}).setdefault(p, Counter())[CLASS[r['class']]] += 1
    return {
        'table': {p: {s: dict(c) for s, c in v.items()} for p, v in table.items()},
        'per_change': {k: {p: dict(c) for p, c in v.items()} for k, v in per_change.items()},
        'schemas': summary,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--reports-dir', type=Path, default=None, help='Live directory containing <schema>/replay-*/report.json')
    ap.add_argument('--out', type=Path, default=HERE / 'replay-policies.json', help='Summary JSON path')
    ap.add_argument('--tex', type=Path, default=ROOT / 'results/gen/replay-policies.tex', help='Output LaTeX macro path')
    a = ap.parse_args()

    if a.reports_dir is None:
        if not a.out.is_file():
            raise SystemExit(f'Missing archived {a.out}')
        out = json.loads(a.out.read_text(encoding='utf-8'))
    else:
        out = aggregate_live(a.reports_dir)
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(json.dumps(out, indent=2) + '\n', encoding='utf-8')

    table = out['table']
    mac = build_macros(table)
    tex = ['% Generated by exp/policy-replay/analyse.py; do not edit.']
    tex += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in sorted(mac.items())]
    a.tex.parent.mkdir(parents=True, exist_ok=True)
    a.tex.write_text('\n'.join(tex) + '\n', encoding='utf-8')
    for p, tag in POLICIES:
        print(tag.ljust(7), '  '.join(
            f"{s}: {table[p][s].get('C', 0)}/{table[p][s].get('W', 0)}/{table[p][s].get('R', 0)} of {table[p][s]['n']}"
            for s in SCOPES
        ))
    print(f'wrote {len(mac)} macros to {a.tex}')


if __name__ == '__main__':
    main()
