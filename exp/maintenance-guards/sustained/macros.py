#!/usr/bin/env python3
"""Sustained concurrent reads and writes (`postgres_sustained_writes`) macro generator.

When run without `--results-dir`, loads archived `summary.json` directly and emits all
`Sw*` LaTeX macros to `--tex` without overwriting `summary.json`. When `--results-dir`
is supplied, aggregates `sustained-writes-*/cell-*.json` and `report.json` into `--out`.
"""
import argparse
import glob
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]


def aggregate_live(results_dir: Path) -> dict:
    cells = [json.loads(Path(f).read_text(encoding="utf-8")) for f in sorted(glob.glob(str(results_dir / "sustained-writes-*/cell-*.json")))]
    if not cells:
        raise SystemExit(f"No sustained-writes-*/cell-*.json found under {results_dir}; refusing to overwrite summary")
    over = None
    for f in sorted(glob.glob(str(results_dir / "sustained-writes-*/report.json"))):
        r = json.loads(Path(f).read_text(encoding="utf-8"))["report"]
        if "trigger_overhead" in r:
            over = r["trigger_overhead"]
    if over is None:
        raise SystemExit(f"Missing trigger_overhead report under {results_dir}")
    rows = {}
    for c in cells:
        a = c["condition_actions"]
        executed = a.get("executed", 0)
        reused = a.get("reused", 0) + a.get("implied", 0) + a.get("merged", 0)
        rows[f"{c['policy']}@{c['rate']}"] = {
            "writes": c["writes"],
            "executed": executed,
            "reused": reused,
            "db_ms_per_use": c["db"]["db_ms"] / c["uses"],
            "uses": c["uses"],
        }
    return {"rows": rows, "trigger_overhead": over}


def build_macros(summary: dict) -> dict[str, str]:
    rows = {tuple(k.split("@", 1)): v for k, v in summary["rows"].items()}
    over = summary["trigger_overhead"]
    mac = {}
    tag = {"0/1": "Zero", "1/8": "Low", "1/2": "Mid", "2/1": "High"}
    for (p, r), v in rows.items():
        t = ("Mavra" if p == "mavra" else "Full") + tag[r]
        mac[f"Sw{t}Checks"] = f"{v['executed']:,}".replace(",", "{,}")
        mac[f"Sw{t}Ms"] = f"{v['db_ms_per_use']:.0f}"
        mac[f"Sw{tag[r]}Writes"] = str(v["writes"])
    m, f = rows[("mavra", "2/1")], rows[("full-recheck", "2/1")]
    mac["SwHighReusePct"] = f"{100 * m['reused'] / (m['reused'] + m['executed']):.0f}"
    mac["SwHighRatio"] = f"{f['executed'] / m['executed']:.1f}"
    mac["SwUses"] = f"{m['uses']:,}".replace(",", "{,}")
    mac["SwTrigMs"] = f"{over['median_ms_with_trigger'] - over['median_ms_without']:.1f}"
    mac["SwTrigPct"] = f"{100 * (over['median_ms_with_trigger'] / over['median_ms_without'] - 1):.1f}"
    return mac


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results-dir", type=Path, default=None, help="Live sustained-writes-* directory")
    ap.add_argument("--out", type=Path, default=HERE / "summary.json", help="Summary JSON path")
    ap.add_argument("--tex", type=Path, default=ROOT / "results/gen/sustained.tex", help="Output LaTeX macro path")
    args = ap.parse_args()

    if args.results_dir is None:
        if not args.out.is_file():
            raise SystemExit(f"Missing archived {args.out}")
        summary = json.loads(args.out.read_text(encoding="utf-8"))
    else:
        summary = aggregate_live(args.results_dir)
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    mac = build_macros(summary)
    tex = ["% Generated by exp/maintenance-guards/sustained/macros.py; do not edit."]
    tex += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(mac.items())]
    args.tex.parent.mkdir(parents=True, exist_ok=True)
    args.tex.write_text("\n".join(tex) + "\n", encoding="utf-8")
    print("\n".join(tex))


if __name__ == "__main__":
    main()
