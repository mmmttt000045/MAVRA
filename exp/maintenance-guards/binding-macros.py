#!/usr/bin/env python3
"""LaTeX macros for the unseen-binding benchmark: binding-report.json -> results/gen/binding.tex."""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument('--tex', type=Path, default=ROOT / 'results/gen/binding.tex')
args = ap.parse_args()

d = json.loads((HERE / 'binding-report.json').read_text(encoding='utf-8'))
pub, rej = d['published'], d['g7_rejected']
mac = {
    'BdBindings': len(d['bindings']),
    'BdPubDefs': pub['definitions'],
    'BdPubSessions': pub['sessions'],
    'BdPubExact': pub['exact_all_bindings'],
    'BdPubChecks': f"{pub['binding_checks']:,}".replace(',', '{,}'),
    'BdPubWrong': pub['binding_wrong'],
    'BdRejDefs': rej['definitions'],
    'BdRejSessions': rej['sessions'],
    'BdRejExact': rej['exact_all_bindings'],
    'BdRejChecks': rej['binding_checks'],
    'BdRejWrong': rej['binding_wrong'],
}
tex = ['% Generated by exp/maintenance-guards/binding-macros.py; do not edit.']
tex += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in sorted(mac.items())]
args.tex.parent.mkdir(parents=True, exist_ok=True)
args.tex.write_text('\n'.join(tex) + '\n', encoding='utf-8')
print('\n'.join(tex))
