#!/usr/bin/env python3
"""Fixed-library replay by maintenance policy on four schemas (no model calls).

The archived replays (TPC-DS: exp/2026-10-02-cache-baseline-tpcds, TPC-H/SSB/BIRD
financial: exp/2026-10-11-generality) hold every policy's outcome per question
instance (library, change, definition, question). The rerun replaces the MAVRA
rows (condition policy, learning-snapshot reference) with the current binary,
which adds the date-key repair; the other policies are unchanged code paths and
keep their archived outcomes. Counts cover the instances present for every policy.
Usage: analyse.py RERUN_DIR [--tex PATH]
"""
import argparse
from collections import Counter
import glob
import gzip
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
ARCHIVE = {'tpcds': ROOT / 'exp/2026-10-02-cache-baseline-tpcds/tpcds-replay-outcomes.json.gz',
           'tpch': ROOT / 'exp/2026-10-11-generality/tpch-replay-report.json.gz',
           'ssb': ROOT / 'exp/2026-10-11-generality/ssb-replay-report.json.gz',
           'financial': ROOT / 'exp/2026-10-11-generality/financial-replay-report.json.gz'}
SCOPES = {'Benign': ['append', 'backfill', 'correct', 'addcol'],
          'Break': ['status', 'revision', 'dupload', 'dimhist', 'latekey'],
          'Outside': ['unit', 'mirror']}
POLICIES = [('revoke', 'Revoke'), ('schema', 'Schema'), ('tabletest', 'Tests'), ('condition', 'Mavra')]
CLASS = {'correct': 'C', 'served_wrong': 'W', 'unavailable_needed': 'R', 'unavailable_unneeded': 'R'}


def key(r):
    # the library name embeds the directory it was loaded from; the last component identifies it
    return (r['lib'].split('/')[-1], r['change'], r['entry'], r['task'])


def main():
    a = argparse.ArgumentParser()
    a.add_argument('rerun')
    a.add_argument('--tex', default=str(ROOT / 'overleaf/gen/replay-policies.tex'))
    a.add_argument('--allow-archived', action='store_true',
                   help='provisional layout only: use the archived MAVRA rows of schemas whose rerun is not finished')
    a = a.parse_args()
    table = {p: {s: Counter() for s in SCOPES} for p, _ in POLICIES}
    per_change = {}
    audit = {}
    for ds, path in ARCHIVE.items():
        old = json.loads(gzip.decompress(path.read_bytes()))['outcomes']
        reports = glob.glob(f'{a.rerun}/{ds}/replay-*/report.json')
        if not reports and a.allow_archived:
            reports = ['archived']
            new = [r for r in old if (r['policy'], r['oracle']) == ('condition', 'snapshot')]
        else:
            assert len(reports) == 1, (ds, reports)
            new = [r for r in json.loads(Path(reports[0]).read_text())['outcomes'] if (r['policy'], r['oracle']) == ('condition', 'snapshot')]
        rows = {p: {key(r): r for r in old if r['policy'] == p and r['oracle'] == 'snapshot'} for p, _ in POLICIES if p != 'condition'}
        rows['condition'] = {key(r): r for r in new}
        common = set.intersection(*[set(v) for v in rows.values()])
        old_mavra = {key(r): r['class'] for r in old if (r['policy'], r['oracle']) == ('condition', 'snapshot')}
        changed = Counter((r['change'], old_mavra.get(k), r['class']) for k, r in rows['condition'].items()
                          if k in common and old_mavra.get(k) != r['class'])
        audit[ds] = {'common': len(common), 'mavra_class_changes': {f'{c}: {o} -> {n}': v for (c, o, n), v in sorted(changed.items())},
                     'new_report': str(Path(reports[0]).relative_to(ROOT)) if Path(reports[0]).is_relative_to(ROOT) else reports[0]}
        for p, _ in POLICIES:
            for k in common:
                r = rows[p][k]
                scope = next(s for s, cs in SCOPES.items() if r['change'] in cs)
                table[p][scope][CLASS[r['class']]] += 1
                table[p][scope]['n'] += 1
                per_change.setdefault(f'{ds}/{r["change"]}', {}).setdefault(p, Counter())[CLASS[r['class']]] += 1
    out = {'table': {p: {s: dict(c) for s, c in v.items()} for p, v in table.items()},
           'per_change': {k: {p: dict(c) for p, c in v.items()} for k, v in per_change.items()}, 'audit': audit}
    (HERE / 'replay-policies.json').write_text(json.dumps(out, indent=2) + '\n')
    mac = {}
    for p, tag in POLICIES:
        for s in SCOPES:
            c = table[p][s]
            for cls in 'CWR':
                mac[f'Rp{tag}{s}{cls}'] = f'{c[cls]:,}'.replace(',', '{,}')
            mac[f'Rp{s}N'] = f"{c['n']:,}".replace(',', '{,}')
    total = sum(table['condition'][s]['n'] for s in SCOPES)
    mac['RpTotal'] = f'{total:,}'.replace(',', '{,}')
    m = table['condition']['Break']
    mac['RpMavraBreakCPct'] = f"{100 * m['C'] / m['n']:.0f}"
    mac['RpSchemaBreakWPct'] = f"{100 * table['schema']['Break']['W'] / table['schema']['Break']['n']:.0f}"
    tex = ['% Generated by exp/2026-11-01-replay-rerun/analyse.py; do not edit.']
    tex += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in sorted(mac.items())]
    Path(a.tex).write_text('\n'.join(tex) + '\n')
    for p, tag in POLICIES:
        print(tag.ljust(7), '  '.join(f"{s}: {table[p][s]['C']}/{table[p][s]['W']}/{table[p][s]['R']} of {table[p][s]['n']}" for s in SCOPES))
    print(json.dumps(audit, indent=1))


if __name__ == '__main__':
    main()
