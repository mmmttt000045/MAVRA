#!/usr/bin/env python3
"""Merge GPU and LLM scaling results for P1-1 into archived JSON and LaTeX macros.

Reads:
  --gpu-summary  path to gpu-summary.json
  --rc           path to risk-coverage.json
  --llm-summary  path to llm-summary.json
Writes:
  exp/2026-11-17-lookup-scale/scale-summary.json
  exp/2026-11-17-lookup-scale/risk-coverage.json
  overleaf/gen/lookup-scale.tex
"""
import argparse
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

ap = argparse.ArgumentParser()
ap.add_argument("--gpu-summary", required=True)
ap.add_argument("--rc", required=True)
ap.add_argument("--llm-summary", required=True)
args = ap.parse_args()

gpu = json.loads(Path(args.gpu_summary).read_text(encoding="utf-8"))
rc = json.loads(Path(args.rc).read_text(encoding="utf-8"))
llm = json.loads(Path(args.llm_summary).read_text(encoding="utf-8"))

merged = {
    "device": gpu["device"],
    "scales": gpu["scales"],
    "subsets": gpu["subsets"],
    "recall_bge_m3": gpu["recall_bge_m3"],
    "name_match": gpu["name_match"],
    "emb_top1": gpu["emb_top1"],
    "tecod_nli_gpu": gpu["tecod_nli_gpu"],
    "cross_encoders": gpu["cross_encoders"],
    "top8_llm_judge": llm["top8_llm_judge"],
    "mavra_confirmed": llm["mavra_confirmed"],
    "train_scale_stats": gpu.get("train_scale_stats", {}),
}

(HERE / "scale-summary.json").write_text(json.dumps(merged, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
(HERE / "risk-coverage.json").write_text(json.dumps(rc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

mac = {}
STAG = {"26": "Base", "100": "C", "500": "D", "1000": "K"}
QTAG = {"orig_96": "Orig", "glm_174": "Glm", "scale_120": "Scale", "all_390": "All"}


def pct(x):
    return f"{100.0 * float(x):.1f}"


def pct0(x):
    return f"{100.0 * float(x):.0f}"


for sc, st in STAG.items():
    # Stage-1 recall & latency
    mac[f"LsRecLat{st}Ms"] = f"{gpu['recall_bge_m3'][sc]['latency_ms_mean']:.0f}"
    for qs, qt in QTAG.items():
        mac[f"LsRecEight{st}{qt}"] = pct(gpu["recall_bge_m3"][sc][qs]["recall@8_all"])
        mac[f"LsRecSixteen{st}{qt}"] = pct(gpu["recall_bge_m3"][sc][qs]["recall@16_all"])
        mac[f"LsName{st}{qt}"] = pct(gpu["name_match"][sc][qs]["exact_rate"])
        mac[f"LsEmb{st}{qt}"] = pct(gpu["emb_top1"][sc][qs]["oracle_exact_rate"])
        mac[f"LsEmbFix{st}{qt}"] = pct(gpu["emb_top1"][sc][qs]["fixed_exact_rate"])
        if sc in gpu.get("tecod_nli_gpu", {}):
            mac[f"LsTecod{st}{qt}"] = pct(gpu["tecod_nli_gpu"][sc][qs]["exact_rate"])
            mac[f"LsTecodLat{st}Ms"] = f"{gpu['tecod_nli_gpu'][sc]['latency_ms_mean']:.0f}"
        if sc in llm.get("top8_llm_judge", {}):
            mac[f"LsTopLlm{st}{qt}"] = pct(llm["top8_llm_judge"][sc][qs]["exact_rate"])
            mac[f"LsTopLlmTok{st}{qt}"] = f"{llm['top8_llm_judge'][sc][qs]['tokens_mean']:.0f}"
            mac[f"LsTopLlmSec{st}{qt}"] = f"{llm['top8_llm_judge'][sc][qs]['seconds_mean']:.1f}"

        # Single CE (zero & refreshed, no-abstain 100% coverage exact rate)
        for ck, ct in [("single_ce_zero", "SceZero"), ("single_ce_refreshed", "SceRef")]:
            if ck in gpu["cross_encoders"]:
                mac[f"Ls{ct}{st}{qt}"] = pct(gpu["cross_encoders"][ck][sc][qs]["no_abstain_exact_rate"])
                mac[f"Ls{ct}Lat{st}Ms"] = f"{gpu['cross_encoders'][ck][sc]['latency_ms_mean']:.0f}"

        # MAVRA first & confirmed (zero-retrain & refreshed)
        for mk, mt in [("mavra_zero", "MavZero"), ("mavra_refreshed", "MavRef")]:
            if mk in gpu["cross_encoders"]:
                ce_row = gpu["cross_encoders"][mk][sc][qs]
                mac[f"Ls{mt}First{st}{qt}"] = pct(ce_row["first_exact_rate"])
                mac[f"Ls{mt}Cov{st}{qt}"] = pct(ce_row["direct_coverage"])
                mac[f"Ls{mt}Prec{st}{qt}"] = pct(ce_row["direct_precision"])
                mac[f"Ls{mt}Risk{st}{qt}"] = pct(ce_row["selective_risk"])
                mac[f"Ls{mt}Lat{st}Ms"] = f"{gpu['cross_encoders'][mk][sc]['latency_ms_mean']:.0f}"
            if mk in llm.get("mavra_confirmed", {}):
                cf_row = llm["mavra_confirmed"][mk][sc][qs]
                mac[f"Ls{mt}Final{st}{qt}"] = pct(cf_row["final_exact_rate"])
                mac[f"Ls{mt}AbsRej{st}{qt}"] = pct(cf_row["absent_reject_rate"])
                mac[f"Ls{mt}Tok{st}{qt}"] = f"{cf_row['tokens_mean']:.0f}"
                mac[f"Ls{mt}Sec{st}{qt}"] = f"{cf_row['seconds_mean']:.2f}"

# Training wall-clock summary for scale-dc
dc_secs = [v["train_seconds"] for k, v in gpu.get("train_scale_stats", {}).items() if k.startswith("scale-dc-")]
if dc_secs:
    mac["LsScaleTrainMeanMin"] = f"{statistics.mean(dc_secs) / 60.0:.1f}"
    mac["LsScaleTrainTotMin"] = f"{sum(dc_secs) / 60.0:.1f}"

tex_lines = ["% Generated by exp/2026-11-17-lookup-scale/analyse_scale.py; do not edit."]
tex_lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(mac.items())]
(ROOT / "overleaf/gen/lookup-scale.tex").write_text("\n".join(tex_lines) + "\n", encoding="utf-8")
print(f"Wrote {len(mac)} macros to overleaf/gen/lookup-scale.tex")
